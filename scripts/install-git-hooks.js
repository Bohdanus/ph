/**
 * Installs the shared git hook entry points and points `core.hooksPath` at them.
 *
 * Runs from `npm install` through the `prepare` script. Idempotent, safe to run
 * by hand, and deliberately unable to fail an install: a tarball build outside a
 * git checkout prints a warning and exits 0.
 *
 * WHY THIS EXISTS INSTEAD OF HUSKY
 * -------------------------------
 * `core.hooksPath` is resolved against the root of whichever worktree git is
 * running in. husky's entry point is `.husky/_`, a directory husky generates
 * during `npm install` and keeps untracked via `.husky/_/.gitignore` (`*`).
 * So `core.hooksPath = .husky/_` resolves to a directory that does not exist in
 * any worktree created with `git worktree add`. Git then finds no hook, runs
 * nothing, and exits 0 — a commit gate that is skipped silently, with no
 * warning and nothing in the commit output to notice.
 *
 * On this repository that was 89 of 118 worktrees, while 96 of the same 118 had
 * a populated `node_modules`. The gate was therefore not "forgot to run npm
 * install" — it was skipped in the one-per-task worktree workflow AGENTS.md
 * mandates, in three quarters of every task in this repo, including the tasks
 * whose entire purpose was fixing failing tests.
 *
 * The fix is an entry point that lives in the common git dir, which every
 * worktree shares, so one install serves all of them. The tracked
 * `.husky/pre-commit` and `.husky/pre-push` are still what actually run, so a
 * worktree that changes the gate exercises its own version of it.
 */

import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/**
 * The hooks installed here. Each one runs the worktree's own `.husky/<name>`.
 *
 * `post-merge` is the odd one out and the asymmetry is deliberate. `pre-commit`,
 * `pre-push` and `pre-merge-commit` GATE: they can stop work, and they do. `post-merge`
 * REPORTS: the merge is already recorded by the time it runs, so a failure in it could
 * not prevent anything and would only leave the operator with a landed merge and an
 * error. It is here to clear claims that the merge just made false — see
 * `scripts/merge-release.mjs`.
 *
 * `pre-merge-commit` is the fourth gate, added because the rule it enforces was written
 * down in more than one place and enforced in none — see `.husky/pre-merge-commit`. Note the
 * limit that comes with it: git runs NO hook for a fast-forward, so that landing shape
 * is uncovered by design rather than by oversight.
 */
const HOOKS = ['pre-commit', 'pre-push', 'pre-merge-commit', 'post-merge'];

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function dispatcher(name) {
  return `#!/usr/bin/env sh
# Generated by scripts/install-git-hooks.js. Do not edit: edit .husky/${name}.
#
# This file lives in the common git dir because \`core.hooksPath\` is resolved
# against the root of the worktree git is running in, and every worktree shares
# this one directory. The worktree's own tracked .husky/${name} is what runs.
#
# HUSKY=0 keeps the escape hatch husky always provided, for a rebase in
# progress rather than as a way around a red gate.
[ "\${HUSKY-}" = "0" ] && exit 0

hook="$(git rev-parse --show-toplevel)/.husky/${name}"
if [ ! -f "$hook" ]; then
\techo "gate: $hook is missing, so there is no gate to run" >&2
\techo "gate: run 'npm install' here, or 'git config --unset core.hooksPath'" >&2
\texit 1
fi

# A checkout from before the shared entry point sources husky's generated
# preamble, which only an install in that worktree ever created. Name it, rather
# than letting sh report a missing path with nothing to connect it to.
if grep -q 'husky\\.sh' "$hook" && [ ! -f "$(dirname "$hook")/_/husky.sh" ]; then
\techo "gate: $hook predates the shared entry point and needs husky's generated preamble." >&2
\techo "gate: bring the worktree up to date (merge or rebase onto main), or run" >&2
\techo "gate: 'npm install' here, or 'git config --unset core.hooksPath'." >&2
\texit 1
fi

sh -e "$hook" "$@"
`;
}

function main() {
  let commonDir;
  try {
    commonDir = git(['rev-parse', '--path-format=absolute', '--git-common-dir']);
  } catch {
    console.warn('gate: not a git checkout, skipping hook install.');
    return;
  }

  const hooksDir = path.join(commonDir, 'hooks-gate');
  mkdirSync(hooksDir, { recursive: true });

  let current = null;
  try {
    current = git(['config', '--get', 'core.hooksPath']);
  } catch {
    // Not set, or set to an empty value.
  }

  // Written before the early return below: a dispatcher whose template changed
  // has to be refreshed even when the path is already correct.
  for (const name of HOOKS) {
    const file = path.join(hooksDir, name);
    writeFileSync(file, dispatcher(name));
    chmodSync(file, 0o755);
  }

  if (current === hooksDir) {
    console.log(`gate: refreshed ${HOOKS.join(', ')} at ${hooksDir} (core.hooksPath unchanged)`);
    return;
  }

  git(['config', 'core.hooksPath', hooksDir]);
  console.log(
    `gate: core.hooksPath ${current === null ? '(unset)' : current} -> ${hooksDir}` +
      (current === '.husky/_' ? '  [was the per-worktree husky path, which worktrees do not have]' : '')
  );
}

main();
